function spiral(cx, cy, r0, r1, turns, n = 90) {
  let d = '';
  for (let i = 0; i <= n; i++) { const t = i / n, r = r0 + (r1 - r0) * t, a = turns * Math.PI * 2 * t - Math.PI / 2; d += (i ? 'L' : 'M') + (cx + Math.cos(a) * r).toFixed(1) + ' ' + (cy + Math.sin(a) * r).toFixed(1); }
  return d;
}
