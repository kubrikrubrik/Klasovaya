/** SVG босса. state: locked | waiting | fight | defeated | opened */
export function bossSVG(id, state = 'waiting', extra = '') {
  return `<svg class="art boss-art" viewBox="-10 -12 260 250" data-boss="${id}">${extra}${bossG(id, state)}</svg>`;
}
const BOSS_FACE = { locked: ['sly', 'a', 's'], waiting: ['sly', 'a', 's'], fight: ['wide', 'a', 'g'], defeated: ['x', 's', 'o'], opened: ['x', 's', 'o'] };
export function bossG(id, state = 'waiting') {
  const f = BOSS_FACE[state] || BOSS_FACE.waiting;
  return `<g class="boss ch boss-${id}" data-state="${state}" data-e="${f[0]}" data-b="${f[1]}" data-m="${f[2]}" data-pose="rest">${BOSS_ART[id]()}</g>`;
}
export function setBossState(el, state) {
  const f = BOSS_FACE[state] || BOSS_FACE.waiting;
  el.setAttribute('data-state', state); el.setAttribute('data-e', f[0]); el.setAttribute('data-b', f[1]); el.setAttribute('data-m', f[2]);
}

